# Runs MediaPipe PoseLandmarker on a base64 JPEG frame; returns knee angle + feedback
@app.post("/analyze")
def analyze(data: AnalyzeInput):
    # Decode base64 → bytes → numpy array → OpenCV BGR image
    img_bytes = base64.b64decode(data.frame)
    arr = np.frombuffer(img_bytes, dtype=np.uint8)
    img = cv2.imdecode(arr, cv2.IMREAD_COLOR)
    if img is None:
        return {"angle": 0, "landmarks": None, "feedback": "Invalid frame"}

    h, w, _ = img.shape
    rgb = cv2.cvtColor(img, cv2.COLOR_BGR2RGB)
    mp_image = mp.Image(image_format=mp.ImageFormat.SRGB, data=rgb)
    result   = pose_landmarker.detect(mp_image)

    if not result.pose_landmarks:
        return {"angle": 0, "landmarks": None, "feedback": "No pose detected"}

    lm    = result.pose_landmarks[0]
    hip   = lm[_LEFT_HIP]
    knee  = lm[_LEFT_KNEE]
    ankle = lm[_LEFT_ANKLE]

    # Normalized coords → pixel space for stable angle calculation
    hip_px   = (hip.x * w,   hip.y * h)
    knee_px  = (knee.x * w,  knee.y * h)
    ankle_px = (ankle.x * w, ankle.y * h)

    # Vectors from knee toward hip and ankle
    v1 = (hip_px[0]   - knee_px[0], hip_px[1]   - knee_px[1])
    v2 = (ankle_px[0] - knee_px[0], ankle_px[1] - knee_px[1])

    angle = math.degrees(
        math.atan2(v2[1], v2[0]) - math.atan2(v1[1], v1[0])
    )
    angle = abs(angle)
    if angle > 180:
        angle = 360 - angle

    if angle > 160:
        feedback = "Good extension!"
    elif angle < 100:
        feedback = "Bend your knee"
    else:
        feedback = "Hold..."

    landmarks = {
        "hip":   {"x": round(hip.x, 4),   "y": round(hip.y, 4)},
        "knee":  {"x": round(knee.x, 4),  "y": round(knee.y, 4)},
        "ankle": {"x": round(ankle.x, 4), "y": round(ankle.y, 4)},
    }

    return {"angle": round(angle, 2), "landmarks": landmarks, "feedback": feedback}
