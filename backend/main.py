# Scores rep quality using the trained RandomForest model
@app.post("/ml/score")
def ml_score(data: MLScoreInput):
    if ml_model is None:
        return {"error": "Model not trained yet. Run ml/train_model.py first"}

    features = [[data.max_angle, data.rep_duration, data.knee_wobble]]
    prediction = ml_model.predict(features)[0]
    proba      = ml_model.predict_proba(features)[0]

    # proba[0] = P(poor), proba[1] = P(good)
    confidence = float(max(proba))
    score      = float(proba[1])   # probability of "good" — used as quality_score 0–1

    return {
        "quality":    "good" if int(prediction) == 1 else "poor",
        "confidence": round(confidence, 3),
        "score":      round(score, 3),
    }


